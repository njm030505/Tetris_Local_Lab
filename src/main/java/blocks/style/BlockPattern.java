package blocks.style;

public enum BlockPattern {
    HORIZONTAL,      // 가로줄 패턴
    DOT,             // 점 패턴
    CROSS,           // 십자 패턴
    DIAGONAL_RIGHT,  // 오른쪽 대각선 패턴 (/)
    DIAGONAL_LEFT,   // 왼쪽 대각선 패턴 (\)
    GRID,            // 격자 패턴
    BRICK,          // 무게추 전용 벽돌 패턴
    VERTICAL         // 세로줄 패턴
}